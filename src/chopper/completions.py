"""Bash completion generation for chopper.

The generated script is written to disk once by ``chopper --completions``.
It does not call back into Python, so it stays a static file.
"""

from __future__ import annotations

import os
import re
import shutil
import subprocess
from pathlib import Path

import click

APP_NAME = "chopper"
BASH_MIN_VERSION = (4, 4)


def completion_script_path(app_name: str = APP_NAME) -> Path:
    """Return the XDG path where the completion script is installed."""
    data_home = os.environ.get("XDG_DATA_HOME", "")
    base = Path(data_home) if data_home else Path.home() / ".local" / "share"
    return base / "bash-completion" / "completions" / app_name


def _choice_words(param: click.Parameter) -> list[str]:
    """Return the completion words for a click Choice parameter."""
    if not isinstance(param.type, click.Choice):
        return []
    words: list[str] = []
    for choice in param.type.choices:
        value = getattr(choice, "value", choice)
        words.append(str(value))
    return words


def _path_action(param: click.Parameter) -> str:
    """Return the bash action used to complete a click Path parameter."""
    if not isinstance(param.type, click.Path):
        return ""
    if not param.type.file_okay and param.type.dir_okay:
        return "_chopper_filedir -d"
    return "_chopper_filedir"


def generate_bash_completion(command: click.Command, app_name: str = APP_NAME) -> str:
    """Build a static bash completion script for a click command."""
    option_words: list[str] = ["-h", "--help"]
    value_cases: dict[str, str] = {}

    for param in command.params:
        if not isinstance(param, click.Option):
            continue

        option_words.extend(param.opts)
        option_words.extend(param.secondary_opts)

        if param.is_flag:
            continue

        choices = _choice_words(param)
        if choices:
            joined = " ".join(choices)
            action = f'COMPREPLY=( $(compgen -W "{joined}" -- "$cur") )'
        else:
            action = _path_action(param)
            if not action:
                continue

        for opt in param.opts:
            value_cases[opt] = action

    unique_options = " ".join(dict.fromkeys(option_words))

    lines = [
        f"# bash completion for {app_name}",
        "# Generated by chopper --completions; do not edit manually.",
        "",
        "_chopper_filedir() {",
        "    if declare -F _filedir >/dev/null 2>&1; then",
        '        _filedir "$@"',
        "        return",
        "    fi",
        "",
        '    local mode="${1:-}"',
        '    if [[ "$mode" == "-d" ]]; then',
        '        COMPREPLY=( $(compgen -d -- "$cur") )',
        "    else",
        '        COMPREPLY=( $(compgen -f -- "$cur") )',
        "    fi",
        "}",
        "",
        "_chopper_completion() {",
        "    local cur prev",
        "    COMPREPLY=()",
        "",
        "    if declare -F _init_completion >/dev/null 2>&1; then",
        "        _init_completion || return",
        "    else",
        '        cur="${COMP_WORDS[COMP_CWORD]}"',
        '        prev="${COMP_WORDS[COMP_CWORD-1]}"',
        "    fi",
        "",
        '    case "$prev" in',
    ]

    for opt, action in value_cases.items():
        lines.extend(
            [
                f"        {opt})",
                f"            {action}",
                "            return",
                "            ;;",
            ]
        )

    lines.extend(
        [
            "    esac",
            "",
            '    if [[ "$cur" == -* ]]; then',
            f'        COMPREPLY=( $(compgen -W "{unique_options}" -- "$cur") )',
            "        return",
            "    fi",
            "",
            "    _chopper_filedir",
            "}",
            "",
            f"complete -o nosort -F _chopper_completion {app_name}",
            "",
        ]
    )

    return "\n".join(lines)


def install_bash_completion(command: click.Command, app_name: str = APP_NAME) -> Path:
    """Write the completion script and return its path."""
    path = completion_script_path(app_name)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        generate_bash_completion(command, app_name),
        encoding="utf-8",
    )
    return path


def get_bash_version() -> tuple[int, int] | None:
    """Return the bash version on PATH, or None when it cannot be read."""
    bash = shutil.which("bash")
    if bash is None:
        return None

    try:
        result = subprocess.run(
            [bash, "--version"],
            capture_output=True,
            text=True,
            check=False,
        )
    except OSError:
        return None

    match = re.search(r"version (\d+)\.(\d+)", result.stdout)
    if match is None:
        return None

    return int(match.group(1)), int(match.group(2))


def bash_version_warning() -> str | None:
    """Return a warning when bash on PATH is too old for the script."""
    version = get_bash_version()
    if version is None or version >= BASH_MIN_VERSION:
        return None

    major, minor = version
    return (
        f"Warning: bash {major}.{minor} found; completions require bash 4.4 "
        "or newer. On macOS, install a newer bash (for example from Homebrew); "
        "zsh is not supported."
    )


def print_install_message(path: Path) -> None:
    """Print the installed path and how to source it."""
    click.echo(f"Completion script written to {path}")
    click.echo()
    click.echo("To enable completions in the current terminal, run:")
    click.echo(f"  source {path}")
